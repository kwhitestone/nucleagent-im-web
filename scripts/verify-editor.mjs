import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
const read = path => JSON.parse(readFileSync(path));
const pin = read("vendor/editor-ui.provenance.json");
const bytes = readFileSync(`vendor/${pin.filename}`);
const hash = (algorithm, encoding) => createHash(algorithm).update(bytes).digest(encoding);
assert.equal(pin.sha256, hash("sha256", "hex"));
assert.equal(pin.filename, `editor-ui-${pin.sha256}.tgz`);
assert.equal(pin.integrity, `sha512-${hash("sha512", "base64")}`);
const dependency = `file:vendor/${pin.filename}`;
assert.equal(read("package.json").dependencies[pin.name], dependency);
const lock = read("package-lock.json");
assert.equal(lock.packages[""].dependencies[pin.name], dependency);
const entry = lock.packages[`node_modules/${pin.name}`];
assert.equal(entry.resolved, dependency);
assert.equal(entry.version, pin.version);
assert.equal(entry.integrity, pin.integrity);
assert.match(pin.sourceCommit, /^[0-9a-f]{40}$/);
console.log(`${pin.name}@${pin.version}: artifact and lock verified`);
